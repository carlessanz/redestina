/**
 * Los dos diccionarios, expuestos para poder comprobarlos.
 *
 * Se exporta por una razón concreta: `t()` cae en silencio al catalán cuando una clave falta
 * en castellano, así que una traducción olvidada no rompe nada y nadie se entera. Con esto,
 * `tests/i18n.test.ts` compara los dos juegos de claves y falla si divergen — que es
 * exactamente el fallo que en la fase 4 dejó cuatro entradas de menú enseñando su
 * identificador, sin que el build dijera nada.
 */
export const DICTS: Record<Lang, Dict> = { ca, es }

interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, params?: Record<string, string | number>) => string
}

const Ctx = createContext<I18nCtx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE) : null
    return saved === 'es' || saved === 'ca' ? saved : 'ca' // por defecto català
  })
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    localStorage.setItem(STORAGE, l)
    document.documentElement.lang = l
  }, [])
  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      // Singular por convención: un texto que cuenta cosas («{n} entitats») canta cuando n
      // vale 1, y se leía «1 entitats han mostrat interès» en el panel del productor. Si
      // existe `<clau>_1`, con n = 1 se usa esa. Es opt-in: una clave sin su `_1` se
      // comporta exactamente como antes, así que no obliga a escribir dos textos por cada
      // número. Solo mira `n` —el contador principal—: un texto con varios contadores que
      // concuerden se redacta para que no cante (ver `proc.e_publicada_gestio_passa`).
      const clau = params !== undefined && Number(params.n) === 1
        && (DICTS[lang][`${key}_1`] ?? DICTS.ca[`${key}_1`]) !== undefined ? `${key}_1` : key
      let s = DICTS[lang][clau] ?? DICTS.ca[clau] ?? key
      if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
      return s
    },
    [lang],
  )
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useT(): I18nCtx {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useT debe usarse dentro de I18nProvider')
  return ctx
}
