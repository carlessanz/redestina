-- ---------------------------------------------------------------------------
-- `codis_postals`: qué municipio hay detrás de un código postal
-- ---------------------------------------------------------------------------
-- PARA QUÉ. Para que al teclear el código postal en la ficha se rellene la población sola.
-- Lo pidió el cliente el 16-09-2026, después de quitar la población del registro: en el
-- alta ya no se pregunta y se completa después, así que ese momento tiene que ser fácil.
-- Escribir el municipio a mano produce «Sant Cugat», «St. Cugat del Vallès» y «SANT CUGAT»
-- para el mismo sitio, y eso es lo que impide que el «mismo municipio +2» de la
-- priorización deje de comparar cadenas (§4, `municipios`).
--
-- DE DÓNDE SALE, que es lo que hace que se pueda mantener: del portal oficial de datos
-- abiertos de la Generalitat, conjunto **«Codis postals per municipis de Catalunya»**
-- (`analisi.transparenciacatalunya.cat`, id `tp8v-a58g`), descargado el 16-09-2026. Misma
-- clase de procedencia que `municipios` —IDESCAT y el portal de datos abiertos— y la misma
-- razón para que **sí vaya en git**: es dato público sin nada personal (§7).
--
-- ⚠️ NO ES UN SERVICIO EXTERNO, y por eso no choca con §7. Es un fichero que se descarga
--    una vez y se siembra aquí; la aplicación no llama a nadie en tiempo de ejecución.
--    Actualizarlo es volver a bajar el CSV y escribir otra migración.
--
-- ⚠️ ES MUCHOS A MUCHOS, y eso decide cómo se usa. Medido sobre las 1.412 parejas reales:
--    **936 de los 1.134 códigos postales (82 %) apuntan a UN solo municipio** —esos se
--    rellenan solos— y 198 apuntan a varios, que es el caso de los códigos compartidos
--    entre pueblos pequeños. Para esos la interfaz tiene que **ofrecer a elegir, no
--    adivinar**: poner el primero sería escribir un dato que nadie ha dicho.
--
-- ⚠️ El `codi_municipi` del CSV trae SEIS cifras —el INE de cinco más un dígito de
--    control—, así que se guarda recortado a cinco para que case con `municipios.codi_ine`.
--    Comprobado antes de sembrar: **947 de 947** municipios de la tabla tienen código
--    postal. Lo único que no casaba eran los centinelas `99998 No consta` y
--    `99999 Altres/Diversos`, que se descartan: no son municipios.
-- ---------------------------------------------------------------------------

create table if not exists codis_postals (
  codi_postal text not null check (codi_postal ~ '^[0-9]{5}$'),
  codi_ine    text not null references municipios (codi_ine),
  primary key (codi_postal, codi_ine)
);

comment on table codis_postals is
  'Código postal ↔ municipio, de dades obertes de la Generalitat (tp8v-a58g, 16-09-2026). Muchos a muchos: un CP puede cubrir varios municipios y un municipio tener varios CP.';

-- El índice que de verdad se usa: siempre se pregunta «qué hay en este CP».
create index if not exists codis_postals_cp_idx on codis_postals (codi_postal);

-- Catálogo público para cualquier autenticado, igual que `municipios` y `productos`: no
-- hay nada personal aquí y filtrarlo por organización no protegería nada.
grant select on codis_postals to authenticated;
alter table codis_postals enable row level security;
drop policy if exists "codis postals: qualsevol autenticat" on codis_postals;
create policy "codis postals: qualsevol autenticat" on codis_postals
  for select to authenticated using (true);

